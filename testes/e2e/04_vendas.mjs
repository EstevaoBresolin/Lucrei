import { abrir, APP, ok, nota, secao, salvar, shot, espera, SQL, dialog, textoErro, toast, escolher } from './lib.mjs'
const { b, page, erros } = await abrir({ storageState: '/tmp/claude-0/e2e/dono.json', acceptDownloads: true })
const saldo = (n) => Number(SQL(`select saldo from produto where nome='${n}'`))
const ultima = () => SQL("select id from venda order by numero desc limit 1")
const lancar = () => page.locator('main aside').getByRole('button', { name: 'Lançar venda' }).click()
const erroVenda = async () => { await espera(700); return (await page.locator('main aside [role=alert]').allInnerTexts()).join(' ') }

secao('Nova venda — validações')
await page.goto(APP + '/vendas/nova'); await page.getByText('Lucro desta venda').waitFor(); await espera(800)
await lancar()
ok(/Adicione pelo menos um produto/.test(await erroVenda()), 'Venda sem produto é bloqueada')
await escolher(page.getByLabel('Onde foi vendido'), /Mercado Livre \(Clássico/)
const prodSel = page.locator('main select').nth(1)
await escolher(prodSel, /Fone Bluetooth X/)
await page.getByLabel('Qtd.').first().fill('0'); await lancar()
ok(/quantidade de cada item/.test(await erroVenda()), 'Quantidade zero é bloqueada')
await page.getByLabel('Qtd.').first().fill('2'); await lancar()
ok(/Informe o preço/.test(await erroVenda()), 'Preço vazio é bloqueado')
await page.getByLabel('Preço unit. (R$)').first().fill('-99')
ok(!(await page.getByLabel('Preço unit. (R$)').first().inputValue()).includes('-'), 'Preço não aceita negativo', await page.getByLabel('Preço unit. (R$)').first().inputValue())
await page.getByLabel('Qtd.').first().fill('50'); await page.getByLabel('Preço unit. (R$)').first().fill('99,90')
ok(/Sem estoque suficiente/.test(await page.locator('main aside').innerText()), 'Avisa quando falta estoque')
await lancar(); const semEst = await erroVenda()
ok(/insuficiente/.test(semEst) && saldo('Fone Bluetooth X') === 12, 'Venda sem estoque é bloqueada', semEst)
await page.getByLabel('Qtd.').first().fill('2')
secao('Nova venda — cálculo e lançamento')
await page.getByLabel('Desconto dado (R$)').fill('500'); await lancar()
ok(/desconto não pode ser maior/.test(await erroVenda()), 'Desconto maior que o valor dos produtos é bloqueado')
await page.getByLabel('Taxa do canal (%)').fill('12'); await page.getByLabel('Frete pago por você (R$)').fill('25')
await page.getByLabel('Imposto (%)').fill('6'); await page.getByLabel('Desconto dado (R$)').fill('9,80'); await page.getByLabel('Outros custos (R$)').fill('3')
await espera(400)
const custoFone = Number(SQL("select custo_medio from produto where nome='Fone Bluetooth X'"))
const receita = 2 * 99.9 - 9.8, lucro = receita - Math.round(receita * 12) / 100 - 25 - Math.round(receita * 6) / 100 - 3 - 2 * custoFone
const painel = await page.locator('main aside').innerText()
const lucroTela = painel.match(/Lucro desta venda\s*(-?\s?R\$\s?[-\d.,]+)/)?.[1]
ok(painel.includes(lucro.toLocaleString('pt-BR', { minimumFractionDigits: 2, maximumFractionDigits: 2 })), 'Lucro calculado na tela confere', `tela ${lucroTela}, esperado R$ ${lucro.toFixed(2)}`)
await page.getByLabel('Nº do pedido no canal').fill('2000001234')
await page.getByLabel('Cliente (opcional)').selectOption({ label: 'Maria Souza' })
await lancar(); await page.waitForURL(/\/vendas\/[0-9a-f-]{36}$/, { timeout: 10000 }).catch(() => {})
ok(/\/vendas\/[0-9a-f-]{36}$/.test(page.url()), 'Lançar venda abre o detalhe')
ok(saldo('Fone Bluetooth X') === 10, 'Venda baixou 2 fones do estoque', `saldo ${saldo('Fone Bluetooth X')}`)
const v1 = SQL(`select receita||'|'||lucro||'|'||status from venda where id='${ultima()}'`)
ok(Math.abs(Number(v1.split('|')[1]) - lucro) < 0.02 && v1.endsWith('|aberta'), 'Venda gravada com o mesmo lucro e situação aberta', v1)
await shot(page, '08-venda-detalhe')

secao('Kit e prejuízo')
await page.goto(APP + '/vendas/nova'); await page.getByText('Lucro desta venda').waitFor(); await espera(800)
await escolher(page.locator('main select').nth(1), /Kit 2 Fones/)
ok(/Kits disponíveis: 5/.test(await page.locator('main').innerText()), 'Kit mostra 5 disponíveis (10 fones)')
await page.getByLabel('Preço unit. (R$)').first().fill('50')
await lancar(); await espera(500)
ok(/dá prejuízo/.test(await page.locator('main aside').innerText()), 'Venda com prejuízo pede confirmação')
await lancar(); await page.waitForURL(/\/vendas\/[0-9a-f-]{36}$/, { timeout: 10000 }).catch(() => {})
ok(saldo('Fone Bluetooth X') === 8, 'Vender o kit baixa 2 fones', `saldo ${saldo('Fone Bluetooth X')}`)
ok(Number(SQL(`select lucro from venda where id='${ultima()}'`)) < 0, 'Venda com prejuízo gravada (após confirmar)')

secao('Venda direta, lançar outra e repetir')
await page.goto(APP + '/vendas/nova'); await page.getByText('Lucro desta venda').waitFor(); await espera(800)
await page.getByLabel('Onde foi vendido').selectOption({ label: 'Venda direta' })
ok((await page.getByLabel('Situação').inputValue()) === 'entregue', 'Venda direta já vem como entregue')
await escolher(page.locator('main select').nth(1), /Prateleira LED 50cm/)
await page.getByLabel('Preço unit. (R$)').first().fill('120'); await page.getByLabel('Forma de pagamento').selectOption('Pix')
await page.locator('main aside').getByRole('button', { name: 'Lançar e começar outra' }).click(); await espera(1500)
ok(/Venda #\d+ lançada/.test(await toast(page)), 'Lançar e começar outra mostra o aviso', await toast(page))
ok((await page.locator('main select').nth(1).inputValue()) === '', 'Formulário limpo para a próxima')
await page.getByRole('button', { name: 'Repetir última venda' }).click(); await espera(800)
ok((await page.getByLabel('Preço unit. (R$)').first().inputValue()) === '120', 'Repetir última venda preenche produto e preço')
const dataInput = page.getByLabel('Data', { exact: true })
await dataInput.fill('2030-01-01'); await espera(200)
await page.getByLabel('Preço unit. (R$)').first().fill('120'); await lancar(); await espera(1500)
const futura = SQL("select data from venda order by numero desc limit 1")
ok(futura !== '2030-01-01', 'Venda com data no futuro é bloqueada', futura === '2030-01-01' ? 'aceitou venda em 01/01/2030' : '')

secao('Detalhe da venda')
const idML = SQL("select id from venda where pedido_externo='2000001234'")
await page.goto(APP + '/vendas/' + idML); await page.getByRole('button', { name: 'Editar venda' }).waitFor()
await page.getByRole('button', { name: /Marcar como enviada/ }).click(); await espera(1000)
ok(SQL(`select status from venda where id='${idML}'`) === 'enviada', 'Marcar como enviada')
await page.getByRole('button', { name: /Marcar como entregue/ }).click(); await espera(1000)
ok(SQL(`select status from venda where id='${idML}'`) === 'entregue', 'Marcar como entregue')
await page.getByRole('button', { name: 'Editar venda' }).click(); let d = dialog(page)
await d.getByLabel('Taxa do canal (%)').fill('150'); await d.getByRole('button', { name: /Salvar/ }).click()
ok(/entre 0 e 100%/.test(await textoErro(d)), 'Editar venda: taxa acima de 100% é bloqueada')
await d.getByLabel('Taxa do canal (%)').fill('12')
await d.getByLabel('Data').fill('2031-05-05'); await d.getByRole('button', { name: /Salvar/ }).click()
ok(/no futuro/.test(await textoErro(d)), 'Editar venda: data no futuro é bloqueada')
await d.getByLabel('Data').fill(new Date().toLocaleDateString('en-CA', { timeZone: 'America/Sao_Paulo' }))
await d.getByLabel('Frete (R$)').fill('30'); await d.getByLabel('Observações').fill('Frete corrigido')
await d.getByRole('button', { name: /Salvar/ }).click(); await espera(1200)
ok(Number(SQL(`select frete from venda where id='${idML}'`)) === 30, 'Editar custos da venda recalcula', SQL(`select frete||' / lucro '||lucro from venda where id='${idML}'`))
await page.getByRole('button', { name: 'Registrar devolução' }).click(); d = dialog(page)
ok(await d.getByRole('button', { name: /Registrar/ }).isDisabled(), 'Devolução sem motivo fica desabilitada')
await d.getByLabel('Motivo').fill('Defeito'); await d.getByRole('button', { name: /Registrar/ }).click(); await espera(1200)
ok(SQL(`select status from venda where id='${idML}'`) === 'devolvida' && saldo('Fone Bluetooth X') === 10, 'Devolução em bom estado volta ao estoque', `saldo ${saldo('Fone Bluetooth X')}`)
const idKit = SQL("select v.id from venda v join venda_item vi on vi.venda_id=v.id join produto p on p.id=vi.produto_id where p.nome='Kit 2 Fones' and v.status='aberta' limit 1")
await page.goto(APP + '/vendas/' + idKit); await page.getByRole('button', { name: 'Cancelar venda' }).waitFor()
await page.getByRole('button', { name: 'Cancelar venda' }).click(); d = dialog(page)
ok(await d.getByRole('button', { name: /Cancelar venda/ }).isDisabled(), 'Cancelar sem motivo fica desabilitado')
await d.getByLabel('Motivo').fill('Comprador desistiu'); await d.getByRole('button', { name: /Cancelar venda/ }).click(); await espera(1200)
ok(SQL(`select status from venda where id='${idKit}'`) === 'cancelada' && saldo('Fone Bluetooth X') === 12, 'Cancelar venda do kit devolve os 2 fones', `saldo ${saldo('Fone Bluetooth X')}`)

secao('Lista de vendas')
await page.goto(APP + '/vendas'); await espera(1200)
const n = await page.locator('tbody tr').count()
ok(n >= 3, 'Lista mostra as vendas', `${n} linhas`)
await page.getByPlaceholder(/Buscar/).fill('2000001234'); await espera(400)
ok((await page.locator('tbody tr').count()) === 1, 'Busca pelo nº do pedido')
await page.getByPlaceholder(/Buscar/).fill('')
await page.locator('main select').nth(1).selectOption('cancelada'); await espera(500)
ok((await page.locator('tbody tr').count()) === 1, 'Filtro por situação')
await page.locator('main select').nth(1).selectOption('')
await page.getByLabel('De').fill('2020-01-01'); await page.getByLabel('Até').fill('2020-01-31'); await espera(800)
ok(/Nenhuma venda neste filtro/.test(await page.locator('main').innerText()), 'Filtro por período')
const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 5000 }).catch(() => null), page.getByRole('button', { name: 'Exportar CSV' }).click()])
ok(!!dl, 'Exportar vendas em CSV')

secao('Painel')
await page.goto(APP + '/'); await espera(2000)
const pain = await page.locator('main').innerText()
ok(/Faturamento/.test(pain) && /Lucro líquido/.test(pain) && /Margem média/.test(pain), 'Painel mostra faturamento, lucro e margem')
const fat = Number(SQL("select coalesce(sum(receita),0) from venda where status not in ('cancelada','devolvida') and data between current_date - 29 and current_date"))
ok(pain.includes(fat.toLocaleString('pt-BR', { minimumFractionDigits: 2, maximumFractionDigits: 2 })), 'Faturamento do painel confere com as vendas', `R$ ${fat.toFixed(2)}`)
ok(/Prateleira LED 50cm/.test(pain), 'Painel mostra alertas de estoque baixo')
await shot(page, '09-painel')
ok(erros.length === 0, 'Sem erros de JavaScript', erros.slice(0, 3).join(' / '))
salvar('/tmp/claude-0/e2e/r04.json'); await b.close()
