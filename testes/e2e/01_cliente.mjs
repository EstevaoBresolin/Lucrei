// Jornada do cliente: página de vendas → criar conta → confirmar e-mail → empresa → teste 30 dias → assinar → pagar
import { abrir, APP, ok, nota, secao, salvar, shot, ultimoEmail, espera } from './lib.mjs'
const EMAIL = `cliente${Date.now()}@teste.com`, SENHA = 'Senha@123'
const { b, page, erros } = await abrir()

secao('Página de vendas')
await page.goto(APP + '/')
ok(await page.getByRole('heading', { name: /quanto sobra/ }).isVisible(), 'Título principal aparece')
ok(!(await page.getByText('Para quem vende no Mercado Livre').count()), 'Selo do topo foi removido')
const precos = await page.locator('#planos').innerText()
ok(/59,90/.test(precos) && /99,00/.test(precos) && /159,00/.test(precos), 'Planos e preços vêm do banco', precos.match(/R\$\s?[\d.,]+/g)?.join(' '))
ok(/100 vendas/.test(precos) && /300 vendas/.test(precos) && /1\.000 vendas/.test(precos), 'Limites de vendas por plano aparecem')
await page.getByText('Preciso de cartão para testar?').click()
ok(await page.getByText('Não. Você cria a conta').isVisible(), 'Dúvidas abrem ao clicar')
await page.getByRole('link', { name: 'Termos de uso' }).first().click(); await page.waitForURL('**/termos')
ok(/30 dias de teste grátis/.test(await page.locator('body').innerText()), 'Termos citam o teste grátis e a cobrança')
await page.goto(APP + '/'); await page.getByRole('link', { name: 'Entrar' }).click(); await page.waitForURL('**/entrar')
await page.getByRole('button', { name: 'Entrar', exact: true }).waitFor({ timeout: 5000 }).catch(() => {})
ok(await page.getByRole('button', { name: 'Entrar', exact: true }).isVisible(), 'Botão Entrar leva para o login')
await page.goto(APP + '/'); await page.getByRole('link', { name: /Testar 30 dias grátis/ }).first().click(); await page.waitForURL('**/cadastro')
ok(await page.getByText('30 dias grátis, sem cartão').isVisible(), 'Botão Testar grátis leva ao cadastro')
await shot(page, '01-cadastro')

secao('Criar conta — validações')
const criar = () => page.getByRole('button', { name: 'Criar conta' }).click()
await criar()
const vazioNome = await page.getByLabel('Seu nome').evaluate((e) => e.validationMessage)
ok(!!vazioNome, 'Nome vazio é bloqueado', vazioNome)
await page.getByLabel('Seu nome').fill('Cliente Teste')
await page.getByLabel('E-mail').fill('email-invalido')
await page.getByLabel('Senha').fill(SENHA)
await criar()
const vEmail = await page.getByLabel('E-mail').evaluate((e) => e.validationMessage)
ok(!!vEmail, 'E-mail inválido é bloqueado', vEmail)
await page.getByLabel('E-mail').fill(EMAIL)
await page.getByLabel('Senha').fill('123')
await criar()
const vSenha = await page.getByLabel('Senha').evaluate((e) => e.validationMessage)
ok(!!vSenha, 'Senha com menos de 6 caracteres é bloqueada', vSenha)
await page.getByLabel('Senha').fill(SENHA)
await criar()
ok(await page.getByText('aceite os Termos de uso').isVisible(), 'Sem aceitar os termos não cria a conta')
await page.getByRole('checkbox').check()
await criar()
await page.getByText('Conta criada. Confirme pelo link').waitFor({ timeout: 10000 }).catch(() => {})
ok(await page.getByText('Conta criada. Confirme pelo link').isVisible(), 'Conta criada pede confirmação por e-mail')
await espera(1500)
const mail = ultimoEmail(EMAIL)
ok(!!mail, 'E-mail de confirmação foi enviado')
const link = mail?.match(/http:\/\/localhost:54321\/auth\/v1\/verify\?[^"\s<]+/)?.[0]
ok(!!link, 'E-mail tem o link de confirmação')
// tentar entrar antes de confirmar
await page.goto(APP + '/entrar')
await page.getByLabel('E-mail').fill(EMAIL); await page.getByLabel('Senha').fill(SENHA)
await page.getByRole('button', { name: 'Entrar' }).click()
await page.getByText('ainda não foi confirmado').waitFor({ timeout: 8000 }).catch(() => {})
ok(await page.getByText('ainda não foi confirmado').isVisible(), 'Login antes de confirmar avisa e oferece reenviar')
// cadastro duplicado
await page.goto(APP + '/cadastro')
await page.getByLabel('Seu nome').fill('Outro'); await page.getByLabel('E-mail').fill(EMAIL); await page.getByLabel('Senha').fill(SENHA)
await page.getByRole('checkbox').check(); await criar(); await espera(2000)
const dup = await page.locator('body').innerText()
ok(/já tem conta/.test(dup) || /Confirme pelo link/.test(dup), 'Cadastro com e-mail repetido', /já tem conta/.test(dup) ? 'avisa que já tem conta' : 'Supabase responde "confirme o e-mail" (não revela se o e-mail existe)')

secao('Confirmação e primeiro acesso')
await espera(1500)
const link2 = ultimoEmail(EMAIL)?.match(/http:\/\/localhost:54321\/auth\/v1\/verify\?[^"\s<]+/)?.[0] ?? link
nota('Reenvio no cadastro repetido', link2 !== link ? 'um novo link foi enviado e o anterior deixou de valer (comportamento padrão do Supabase)' : 'mesmo link')
await page.goto(link2)
await page.waitForURL(APP + '/**', { timeout: 15000 })
await page.getByText('Vamos montar o Apura').waitFor({ timeout: 15000 }).catch(() => {})
ok(await page.getByText('Vamos montar o Apura').isVisible(), 'Link do e-mail confirma e entra direto (termos já aceitos no cadastro)')
await shot(page, '02-criar-empresa')
await page.getByRole('button', { name: 'Criar minha empresa' }).click()
ok(await page.getByText('Dê um nome à sua loja').isVisible(), 'Empresa sem nome é bloqueada')
await page.getByLabel('Nome da loja ou empresa').fill('Loja do Cliente Teste')
await page.getByRole('button', { name: 'Criar minha empresa' }).click()
ok(await page.getByText('Escolha como você trabalha').isVisible(), 'Empresa sem tipo é bloqueada')
await page.getByText('Compro pronto e revendo').click()
await page.getByRole('button', { name: 'Criar minha empresa' }).click()
await page.getByText('Teste grátis:').waitFor({ timeout: 15000 }).catch(() => {})
const faixa = await page.getByText('Teste grátis:').locator('..').innerText().catch(() => '')
ok(/faltam 30 dias/.test(faixa), 'Faixa do teste mostra 30 dias', faixa.replace(/\s+/g, ' '))
await shot(page, '03-painel-teste')
const menu = await page.locator('aside nav').innerText()
ok(!/Produção|Insumos/.test(menu), 'Revenda: Produção e Insumos escondidos do menu', menu.replace(/\n/g, ' · '))
ok(/Assinatura/.test(menu), 'Menu tem Assinatura')

secao('Assinatura (Asaas simulado)')
await page.getByRole('link', { name: 'Ver planos' }).click(); await page.waitForURL('**/assinatura')
await page.getByText('Escolha seu plano').waitFor()
ok(/Teste grátis · 30 dias/.test(await page.locator('main').innerText()), 'Situação: teste grátis 30 dias')
await page.getByRole('button', { name: /Inicial/ }).first().click()
await page.getByRole('button', { name: /^Assinar Inicial/ }).click()
ok(await page.getByText('Informe o CPF ou CNPJ').isVisible(), 'Assinar sem CPF/CNPJ é bloqueado')
await page.getByLabel('CPF ou CNPJ de quem paga').fill('12345678909')
ok((await page.getByLabel('CPF ou CNPJ de quem paga').inputValue()) === '123.456.789-09', 'Máscara de CPF', await page.getByLabel('CPF ou CNPJ de quem paga').inputValue())
await page.getByLabel('CPF ou CNPJ de quem paga').fill('11222333000181')
ok((await page.getByLabel('CPF ou CNPJ de quem paga').inputValue()) === '11.222.333/0001-81', 'Máscara de CNPJ', await page.getByLabel('CPF ou CNPJ de quem paga').inputValue())
await page.getByLabel('CPF ou CNPJ de quem paga').fill('123')
await page.getByRole('button', { name: /^Assinar Inicial/ }).click()
ok(await page.getByText('Informe o CPF ou CNPJ').isVisible(), 'CPF incompleto é bloqueado')
await page.getByLabel('CPF ou CNPJ de quem paga').fill('12345678909')
await page.getByRole('button', { name: /^Assinar Inicial/ }).click()
await page.waitForURL('**/__fatura/**', { timeout: 15000 }).catch(() => {})
ok(page.url().includes('/__fatura/'), 'Assinar leva para a página de pagamento do Asaas')
const asaas = await (await fetch('http://localhost:54321/__asaas')).json()
const sub = Object.values(asaas.assinaturas)[0]
const fimTeste = new Date(Date.now() + 30 * 864e5).toLocaleDateString('en-CA', { timeZone: 'America/Sao_Paulo' })
ok(sub && sub.value === 59.9 && sub.billingType === 'UNDEFINED' && sub.cycle === 'MONTHLY', 'Assinatura criada no Asaas: R$ 59,90 mensal, Pix/boleto/cartão', JSON.stringify({ v: sub?.value, t: sub?.billingType, c: sub?.cycle }))
ok(sub?.nextDueDate === fimTeste, '1ª cobrança vence no fim do teste (não perde dias grátis)', `${sub?.nextDueDate} (esperado ${fimTeste})`)
ok(asaas.clientes[0]?.cpfCnpj === '12345678909' && asaas.clientes[0]?.email === EMAIL, 'Cliente criado no Asaas com CPF e e-mail')
// volta ao sistema antes de pagar
await page.goto(APP + '/assinatura'); await page.getByText('Situação').waitFor()
ok(!/Assinatura feita|Teste grátis:/.test(await page.locator('main').innerText()), 'Depois de assinar no teste, a faixa de aviso some')
// pagar
await page.goto(Object.values(asaas.pagamentos)[0].invoiceUrl)
await page.getByRole('link', { name: 'Pagar com Pix' }).click()
ok(/webhook 200/.test(await page.locator('#webhook').innerText()), 'Asaas avisa o pagamento (webhook aceito)')
await page.goto(APP + '/assinatura'); await page.getByText('Situação').waitFor(); await espera(800)
const sit = await page.locator('main').innerText()
ok(/Ativa/.test(sit), 'Depois de pagar a assinatura fica Ativa')
ok(/Pago até/.test(sit), 'Mostra até quando está pago', sit.match(/Pago até\s*\S+/)?.[0])
ok(!(await page.getByText('Teste grátis:').count()), 'Faixa do teste some depois de pago')
await shot(page, '04-assinatura-ativa')

secao('Trocar plano e cancelar')
await page.getByRole('button', { name: /Crescimento/ }).first().click()
await page.getByRole('button', { name: /Trocar para Crescimento/ }).click()
await page.getByText('Plano trocado para Crescimento').waitFor({ timeout: 10000 }).catch(() => {})
ok(await page.getByText('Plano trocado para Crescimento').isVisible(), 'Troca de plano funciona')
const a2 = await (await fetch('http://localhost:54321/__asaas')).json()
ok(Object.values(a2.assinaturas)[0].value === 99, 'Valor da assinatura atualizado no Asaas para R$ 99')
await page.getByRole('button', { name: 'Cancelar assinatura' }).click()
await page.getByRole('dialog').getByRole('button', { name: 'Cancelar assinatura' }).click()
await page.getByText('Assinatura cancelada.').first().waitFor({ timeout: 10000 }).catch(() => {})
const pos = await page.locator('main').innerText()
ok(/Assinatura cancelada/.test(pos) && /Acesso até/.test(pos), 'Cancelar mantém acesso até a data paga')

secao('Esqueci minha senha')
await page.getByRole('button', { name: 'Sair' }).first().click().catch(() => {})
await page.goto(APP + '/entrar'); await page.getByRole('button', { name: 'Esqueci minha senha' }).click()
await page.getByLabel('E-mail').fill(EMAIL); await page.getByRole('button', { name: 'Enviar link' }).click()
await page.getByText('enviamos um link').waitFor({ timeout: 8000 }).catch(() => {})
ok(await page.getByText('enviamos um link').isVisible(), 'Pedido de nova senha confirma o envio')
await espera(1500)
const rec = ultimoEmail(EMAIL)?.match(/http:\/\/localhost:54321\/auth\/v1\/verify\?[^"\s<]+type=recovery[^"\s<]*/)?.[0]
ok(!!rec, 'E-mail de nova senha chegou')
if (rec) {
  await page.goto(rec); await page.getByRole('textbox', { name: /^Nova senha/ }).waitFor({ timeout: 10000 })
  await page.getByRole('textbox', { name: /^Nova senha/ }).fill('Nova@123'); await page.getByLabel('Repita a nova senha').fill('Outra@123')
  await page.getByRole('button', { name: 'Salvar nova senha' }).click()
  ok(await page.getByText('As duas senhas não são iguais').isVisible(), 'Senhas diferentes são bloqueadas')
  await page.getByLabel('Repita a nova senha').fill('Nova@123'); await page.getByRole('button', { name: 'Salvar nova senha' }).click()
  await page.locator('aside').waitFor({ timeout: 10000 }).catch(() => {})
  ok(await page.locator('aside').isVisible(), 'Nova senha salva e entra no sistema')
  await page.getByRole('button', { name: 'Sair' }).first().click()
  await page.goto(APP + '/entrar'); await page.getByLabel('E-mail').fill(EMAIL); await page.getByLabel('Senha').fill(SENHA)
  await page.getByRole('button', { name: 'Entrar' }).click(); await page.getByText('incorretos').waitFor({ timeout: 8000 }).catch(() => {})
  ok(await page.getByText('E-mail ou senha incorretos').isVisible(), 'Senha antiga não entra mais')
}
ok(erros.length === 0, 'Sem erros de JavaScript no navegador', erros.slice(0, 3).join(' / '))
salvar('/tmp/claude-0/e2e/r01.json'); await b.close()
