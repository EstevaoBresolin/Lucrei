import { abrir, APP, ok, nota, secao, salvar, shot, espera, SQL, dialog, textoErro, toast } from './lib.mjs'
const { b, page, erros } = await abrir({ storageState: '/tmp/claude-0/e2e/dono.json', acceptDownloads: true })
const saldo = (n) => Number(SQL(`select saldo from produto where nome='${n}'`))
const saldoM = (n) => Number(SQL(`select saldo from material where nome='${n}'`))

secao('Estoque — movimentar produto')
await page.goto(APP + '/estoque'); await page.getByRole('tab', { name: 'Produtos' }).waitFor(); await espera(800)
const linhaFone = page.getByRole('row', { name: /Fone Bluetooth X/ })
await linhaFone.getByRole('button', { name: 'Movimentar' }).click(); let d = dialog(page)
await d.getByRole('button', { name: 'Registrar' }).click()
