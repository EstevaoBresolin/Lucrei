await d.getByLabel(/Quantidade/).fill('-5')
ok(!(await d.getByLabel(/Quantidade/).inputValue()).includes('-'), 'Quantidade não aceita negativo', await d.getByLabel(/Quantidade/).inputValue())
await d.getByLabel(/Quantidade/).fill('10'); await d.getByRole('button', { name: 'Registrar' }).click(); await espera(1000)
ok(saldo('Fone Bluetooth X') === 10, 'Entrada de 10 (usa o custo atual quando vazio)', `saldo ${saldo('Fone Bluetooth X')}`)
await linhaFone.getByRole('button', { name: 'Movimentar' }).click(); d = dialog(page)
await d.getByLabel('O que aconteceu?').selectOption('perda'); await d.getByLabel(/Quantidade/).fill('1'); await d.getByRole('button', { name: 'Registrar' }).click()
ok(/Informe o motivo/.test(await textoErro(d)), 'Perda sem motivo é bloqueada')
await d.getByLabel('Motivo').fill('Caiu no chão'); await d.getByRole('button', { name: 'Registrar' }).click(); await espera(1000)
ok(saldo('Fone Bluetooth X') === 9, 'Perda baixa 1', `saldo ${saldo('Fone Bluetooth X')}`)
await linhaFone.getByRole('button', { name: 'Movimentar' }).click(); d = dialog(page)
await d.getByLabel('O que aconteceu?').selectOption('uso_interno'); await d.getByLabel(/Quantidade/).fill('100'); await d.getByLabel('Motivo').fill('teste')
await d.getByRole('button', { name: 'Registrar' }).click()
const errSaldo = await textoErro(d)
ok(!!errSaldo && saldo('Fone Bluetooth X') === 9, 'Saída maior que o saldo é bloqueada', errSaldo)
await d.getByLabel('O que aconteceu?').selectOption('ajuste'); await d.getByLabel(/Saldo correto/).fill('9'); await d.getByRole('button', { name: 'Registrar' }).click()
ok(/igual ao atual/.test(await textoErro(d)), 'Ajuste para o mesmo saldo é bloqueado')
await d.getByLabel(/Saldo correto/).fill('8')
ok(/Diferença: -1/.test(await d.innerText()), 'Ajuste mostra a diferença')
await d.getByLabel('Motivo').fill('Contagem'); await d.getByRole('button', { name: 'Registrar' }).click(); await espera(1000)
ok(saldo('Fone Bluetooth X') === 8, 'Ajuste de saldo', `saldo ${saldo('Fone Bluetooth X')}`)
const kitLinha = page.getByRole('row', { name: /Kit 2 Fones/ })
const kitTxt = await kitLinha.innerText().catch(() => '')
nota('Kit na tela de Estoque', kitTxt ? kitTxt.replace(/\s+/g, ' ') : 'kits não aparecem na aba Produtos do Estoque (não têm saldo próprio); o disponível aparece no cadastro do kit e na Nova venda')

secao('Estoque — insumos, movimentações, inventário')
await page.getByRole('tab', { name: 'Insumos' }).click(); await espera(600)
ok(/Chapa MDF 15mm/.test(await page.locator('main').innerText()), 'Aba de insumos lista os insumos')
await page.getByRole('row', { name: /Parafuso/ }).getByRole('button', { name: 'Movimentar' }).click(); d = dialog(page)
await d.getByLabel(/Quantidade/).fill('50'); await d.getByLabel(/Custo por un/).fill('0,20'); await d.getByRole('button', { name: 'Registrar' }).click(); await espera(1000)
ok(saldoM('Parafuso') === 250 && Math.abs(Number(SQL("select custo_medio from material where nome='Parafuso'")) - 0.12) < 0.001, 'Entrada de insumo recalcula o custo médio (200 a 0,10 + 50 a 0,20 = 0,12)', SQL("select saldo||' a '||custo_medio from material where nome='Parafuso'"))
await page.getByRole('tab', { name: 'Movimentações' }).click(); await espera(800)
const movs = await page.locator('main').innerText()
ok(/Perda/.test(movs) && /Caiu no chão/.test(movs), 'Movimentações mostram o histórico com motivo')
const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 5000 }).catch(() => null), page.getByRole('button', { name: 'CSV' }).click()])
ok(!!dl && /movimentacoes\.csv/.test(dl.suggestedFilename()), 'Exportar movimentações em CSV')
const [dl2] = await Promise.all([page.waitForEvent('download', { timeout: 5000 }).catch(() => null), page.getByRole('button', { name: 'Exportar estoque' }).click()])
ok(!!dl2, 'Exportar estoque', dl2?.suggestedFilename())
await page.getByRole('tab', { name: 'Inventário' }).click(); await espera(600)
await page.getByRole('button', { name: 'Contar produtos' }).click(); await espera(1200)
const campoFone = page.getByLabel('Contado de Fone Bluetooth X')
ok(await campoFone.isVisible(), 'Inventário abre a lista para contar')
await campoFone.fill('7'); await page.getByText('Inventário').first().click(); await espera(800)
await page.getByRole('button', { name: 'Concluir e ajustar' }).click(); await espera(400)
if (await page.getByRole('dialog').count()) await page.getByRole('dialog').getByRole('button').last().click()
await espera(1200)
ok(saldo('Fone Bluetooth X') === 7, 'Concluir inventário ajusta o saldo para o contado', `saldo ${saldo('Fone Bluetooth X')}`)
ok(saldo('Prateleira LED 50cm') === 0, 'Itens não contados ficam como estavam', `prateleira ${saldo('Prateleira LED 50cm')}`)

secao('Compras')
await page.goto(APP + '/compras'); await espera(800)
await page.getByRole('button', { name: 'Nova compra' }).click(); d = dialog(page)
await d.getByRole('button', { name: 'Lançar compra' }).click()
ok(/Adicione pelo menos um item/.test(await textoErro(d)), 'Compra sem item é bloqueada')
await d.getByLabel('Fornecedor').selectOption({ label: 'Madeireira Silva' })
await d.getByLabel('Item', { exact: false }).first().selectOption({ label: 'Fita LED 3000K' })
await d.getByLabel(/^Qtd\./).first().fill('10')
await d.getByRole('button', { name: 'Lançar compra' }).click(); await espera(1200)
const semPreco = !(await d.isVisible())
ok(!semPreco, 'Compra sem preço do item é bloqueada', semPreco ? 'lançou a compra com preço vazio (entra a R$ 0 e derruba o custo médio)' : await textoErro(d))
if (semPreco) { nota('Custo médio após compra sem preço', SQL("select saldo||' m a '||custo_medio from material where nome='Fita LED 3000K'")); await page.getByRole('button', { name: 'Nova compra' }).click(); d = dialog(page); await d.getByLabel('Fornecedor').selectOption({ label: 'Madeireira Silva' }); await d.getByLabel('Item', { exact: false }).first().selectOption({ label: 'Fita LED 3000K' }); await d.getByLabel(/^Qtd\./).first().fill('10') }
const antesFita = saldoM('Fita LED 3000K')
await d.getByLabel('Desconto (R$)').fill('999'); await d.getByLabel(/^Preço por/).first().fill('3,00'); await d.getByRole('button', { name: 'Lançar compra' }).click()
ok(/desconto não pode ser maior/.test(await textoErro(d)), 'Compra com desconto maior que o total é bloqueada')
await d.getByLabel('Desconto (R$)').fill('0')
await d.getByRole('button', { name: 'Adicionar item' }).click()
await d.getByLabel('Item', { exact: false }).nth(1).selectOption({ label: 'Fone Bluetooth X' })
await d.getByLabel(/^Qtd\./).nth(1).fill('5'); await d.getByLabel(/^Preço por/).nth(1).fill('40')
await d.getByLabel('Frete (R$)').fill('20'); await d.getByLabel('Nº da nota fiscal').fill('1234')
ok(/Total/.test(await d.innerText()), 'Compra mostra o total')
await d.getByRole('button', { name: 'Lançar compra' }).click(); await espera(1500)
ok(saldoM('Fita LED 3000K') === antesFita + 10 && saldo('Fone Bluetooth X') === 12, 'Compra recebida dá entrada nos dois itens', `fita ${saldoM('Fita LED 3000K')}, fone ${saldo('Fone Bluetooth X')}`)
const custoFone = Number(SQL("select custo_medio from produto where nome='Fone Bluetooth X'"))
nota('Custo do fone após compra com frete rateado', `custo médio ${custoFone.toFixed(4)} (7 un a 45,90 + 5 un a 40 + parte do frete)`)
ok(custoFone > 40 && custoFone < 46, 'Custo médio do fone recalculado com o frete', custoFone.toFixed(2))
await page.getByRole('button', { name: 'Nova compra' }).click(); d = dialog(page)
await d.getByLabel('Item', { exact: false }).first().selectOption({ label: 'Fonte 12V 2A' }); await d.getByLabel(/^Qtd\./).first().fill('10'); await d.getByLabel(/^Preço por/).first().fill('6')
await d.getByLabel(/Já recebi/).uncheck(); await d.getByRole('button', { name: 'Lançar compra' }).click(); await espera(1200)
ok(SQL("select status from compra order by numero desc limit 1") === 'pedida' && saldoM('Fonte 12V 2A') === 20, 'Compra pedida não mexe no estoque')
await page.getByRole('button', { name: /Editar compra/ }).first().click(); d = dialog(page)
await d.getByLabel(/^Qtd\./).first().fill('12'); await d.getByRole('button', { name: 'Salvar compra' }).click(); await espera(1200)
ok(Number(SQL("select qtd_compra from compra_item ci join compra c on c.id=ci.compra_id order by c.numero desc limit 1")) === 12, 'Editar compra pedida')
await page.getByRole('button', { name: 'Receber' }).first().click(); await espera(400)
if (await page.getByRole('dialog').count()) await page.getByRole('dialog').getByRole('button').last().click()
await espera(1200)
ok(saldoM('Fonte 12V 2A') === 32, 'Receber compra pedida dá entrada', `fonte ${saldoM('Fonte 12V 2A')}`)
await page.getByRole('button', { name: 'Nova compra' }).click(); d = dialog(page)
await d.getByLabel('Item', { exact: false }).first().selectOption({ label: 'Parafuso' }); await d.getByLabel(/^Qtd\./).first().fill('1'); await d.getByLabel(/^Preço por/).first().fill('1')
await d.getByLabel(/Já recebi/).uncheck(); await d.getByRole('button', { name: 'Lançar compra' }).click(); await espera(1200)
const nCompras = Number(SQL('select count(*) from compra'))
await page.getByRole('button', { name: /Excluir compra/ }).first().click(); await page.getByRole('dialog').getByRole('button', { name: /Excluir/ }).click(); await espera(1200)
ok(Number(SQL('select count(*) from compra')) === nCompras - 1, 'Excluir compra pedida')
await shot(page, '06-compras')

secao('Produção')
await page.goto(APP + '/producao'); await espera(1000)
const podeMontar = await page.getByText('Dá para montar agora').locator('xpath=ancestor::*[self::section or self::div][2]').innerText().catch(() => '')
