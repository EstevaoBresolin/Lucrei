await page.getByRole('button', { name: 'Nova ordem' }).click(); d = dialog(page)
await d.getByRole('button', { name: 'Criar ordem' }).click()
ok(/Escolha o produto e a quantidade/.test(await textoErro(d)), 'Ordem vazia é bloqueada')
await d.getByLabel('Produto').selectOption({ label: 'Prateleira LED 50cm' }); await d.getByLabel('Quantidade').fill('0')
await d.getByRole('button', { name: 'Criar ordem' }).click()
ok(/Escolha o produto e a quantidade/.test(await textoErro(d)), 'Ordem com quantidade zero é bloqueada')
await d.getByLabel('Quantidade').fill('2'); await d.getByRole('button', { name: 'Criar ordem' }).click(); await espera(1200)
ok(SQL("select status||' '||quantidade from ordem_producao order by numero desc limit 1").startsWith('planejada 2'), 'Ordem criada como planejada')
await page.getByRole('button', { name: 'Iniciar produção' }).click(); await espera(900)
ok(SQL("select status from ordem_producao order by numero desc limit 1") === 'em_montagem', 'Iniciar produção')
const fitaAntes = saldoM('Fita LED 3000K'), fonteAntes = saldoM('Fonte 12V 2A')
await page.getByRole('button', { name: 'Concluir', exact: true }).click(); d = dialog(page); await espera(800)
ok(/Fita LED 3000K/.test(await d.innerText()), 'Concluir mostra o consumo previsto dos insumos')
const inputs = d.locator('input'); const nIn = await inputs.count()
for (let i = 0; i < nIn; i++) { const row = await inputs.nth(i).locator('xpath=ancestor::tr[1]').innerText(); if (/Fita/.test(row)) await inputs.nth(i).fill('1,2') }
await d.getByRole('button', { name: 'Concluir e dar entrada' }).click(); await espera(1500)
ok(saldo('Prateleira LED 50cm') === 2, 'Produção concluída dá entrada de 2 prateleiras', `saldo ${saldo('Prateleira LED 50cm')}`)
ok(Math.abs(saldoM('Fita LED 3000K') - (fitaAntes - 1.2)) < 0.001 && saldoM('Fonte 12V 2A') === fonteAntes - 2, 'Baixa os insumos (fita com consumo real 1,2 m; fonte 2 un previstas)', `fita ${saldoM('Fita LED 3000K')}, fonte ${saldoM('Fonte 12V 2A')}`)
ok(Number(SQL("select custo_medio from produto where nome='Prateleira LED 50cm'")) > 0, 'Prateleira ganhou custo real da produção', SQL("select custo_medio from produto where nome='Prateleira LED 50cm'"))
await page.getByRole('button', { name: 'Nova ordem' }).click(); d = dialog(page)
await d.getByLabel('Produto').selectOption({ label: 'Prateleira LED 50cm' }); await d.getByLabel('Quantidade').fill('1000'); await d.getByRole('button', { name: 'Criar ordem' }).click(); await espera(1200)
await page.getByRole('button', { name: 'Concluir', exact: true }).click(); d = dialog(page); await espera(600)
await d.getByRole('button', { name: 'Concluir e dar entrada' }).click(); await espera(1200)
const errProd = await textoErro(d)
ok(!!errProd, 'Produzir sem insumos suficientes é bloqueado', errProd)
await d.getByRole('button', { name: 'Voltar' }).click()
await page.getByRole('button', { name: 'Cancelar', exact: true }).click(); await espera(1000)
ok(SQL("select status from ordem_producao order by numero desc limit 1") === 'cancelada', 'Cancelar ordem')
await page.getByRole('button', { name: /Excluir ordem/ }).first().click(); await espera(400)
if (await page.getByRole('dialog').count()) await page.getByRole('dialog').getByRole('button', { name: /Excluir/ }).click()
await espera(1000)
ok(SQL("select count(*) from ordem_producao where status='cancelada'") === '0', 'Excluir ordem cancelada')
await shot(page, '07-producao')
ok(erros.length === 0, 'Sem erros de JavaScript', erros.slice(0, 3).join(' / '))
salvar('/tmp/claude-0/e2e/r03.json'); await b.close()
