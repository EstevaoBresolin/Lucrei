// Pagamentos de compra em partes e Finanças sem o Mercado Livre
import { abrir, APP, ok, secao, salvar, espera, SQL, dialog, textoErro, novoUsuario, KEYS_ } from './lib.mjs'
const { b, page, erros } = await abrir({ storageState: '/tmp/claude-0/e2e/dono.json' })
const EMP = SQL("select id from empresa where nome='Fábrica Teste'")
const saldoConta = (n) => Number(SQL(`select set_config('request.jwt.claim.role','service_role',false), set_config('app.empresa','${EMP}',false); select saldo from vw_conta_saldo where nome='${n}' and empresa_id='${EMP}'`).split('\n').pop())
const pagoDe = (num) => Number(SQL(`select coalesce(sum(p.valor),0) from compra_pagamento p join compra c on c.id=p.compra_id where c.empresa_id='${EMP}' and c.numero=${num}`))
const ultima = () => Number(SQL(`select max(numero) from compra where empresa_id='${EMP}'`))
const estoque = () => Number(SQL(`select saldo from produto where nome='Fone Bluetooth X' and empresa_id='${EMP}'`))
const S0 = saldoConta('Mercado Pago')

secao('Compra com adiantamento')
await page.goto(APP + '/compras'); await espera(1200)
await page.getByRole('button', { name: 'Nova compra' }).click(); let d = dialog(page)
await d.getByLabel('Item', { exact: false }).first().selectOption({ label: 'Fone Bluetooth X' })
await d.getByLabel(/^Qtd\./).first().fill('10'); await d.getByLabel(/^Preço por/).first().fill('20')
await d.getByLabel(/Já recebi/).uncheck()
await d.getByLabel('Pago agora (R$)').fill('500'); await d.getByRole('button', { name: 'Lançar compra' }).click()
ok(/não pode passar do total/.test(await textoErro(d)), 'Pago agora maior que o total é bloqueado')
await d.getByLabel('Pago agora (R$)').fill('100'); await d.getByRole('button', { name: 'Lançar compra' }).click(); await espera(1500)
const N = ultima(); const est0 = estoque()
ok(pagoDe(N) === 100 && SQL(`select status from compra where empresa_id='${EMP}' and numero=${N}`) === 'pedida', 'Compra pedida com adiantamento de 100 lançada', `pago ${pagoDe(N)}`)
ok(saldoConta('Mercado Pago') === S0 - 100, 'O adiantamento já sai do saldo, antes de receber', String(saldoConta('Mercado Pago')))
ok(/Falta R\$\s?100,00/.test(await page.locator('main').innerText()), 'Lista de compras mostra quanto falta pagar')

secao('Pagar o resto pela aba Finanças')
await page.goto(APP + '/financas'); await espera(1500)
let t = await page.locator('main').innerText()
ok(/A pagar de compras/.test(t) && new RegExp(`#${N}`).test(t), 'Finanças lista a compra em aberto')
ok(!/A receber do Mercado Livre|Atualizar do ML|Libera nos próximos/.test(t), 'Sem a parte de a receber do Mercado Livre')
await page.getByRole('row', { name: new RegExp(`#${N}`) }).getByRole('button', { name: 'Pagar' }).click(); d = dialog(page)
ok((await d.getByLabel('Valor pago (R$)').inputValue()) === '100', 'Pagamento já vem com o que falta', await d.getByLabel('Valor pago (R$)').inputValue())
await d.getByLabel('Valor pago (R$)').fill('150'); await d.getByRole('button', { name: 'Lançar pagamento' }).click()
ok(/passa do que falta pagar/.test(await textoErro(d)), 'Pagar mais do que falta é bloqueado')
await d.getByLabel('Valor pago (R$)').fill('60'); await d.getByLabel('Observação (opcional)').fill('Segunda parcela')
await d.getByRole('button', { name: 'Lançar pagamento' }).click(); await espera(1500)
ok(pagoDe(N) === 160 && saldoConta('Mercado Pago') === S0 - 160, 'Segunda parcela de 60 sai do saldo', `${pagoDe(N)} / ${saldoConta('Mercado Pago')}`)
await page.getByRole('row', { name: new RegExp(`#${N}`) }).getByRole('button', { name: 'Pagar' }).click(); d = dialog(page)
await d.getByText('Segunda parcela').waitFor({ timeout: 5000 }).catch(() => {})
ok(/Segunda parcela/.test(await d.innerText()), 'Pagamentos anteriores aparecem no histórico')
await d.getByRole('button', { name: 'Lançar pagamento' }).click(); await espera(1500)
ok(pagoDe(N) === 200 && saldoConta('Mercado Pago') === S0 - 200, 'Restante pago: total de 200 saiu do saldo')
t = await page.locator('main').innerText()
ok(!new RegExp(`#${N}\\b`).test(t.split('Extrato')[0]), 'Compra paga sai da lista de a pagar')
ok(/Pagamento da compra #/.test(t), 'Extrato mostra os pagamentos da compra')

secao('Receber depois de pago')
await page.goto(APP + '/compras'); await espera(1200)
await page.getByRole('row', { name: new RegExp(`#${N}`) }).getByRole('button', { name: 'Receber' }).click(); await espera(1500)
ok(estoque() === est0 + 10, 'Receber dá entrada no estoque', `${est0} → ${estoque()}`)
ok(saldoConta('Mercado Pago') === S0 - 200, 'Receber não desconta de novo do saldo', String(saldoConta('Mercado Pago')))
ok(/Paga/.test(await page.getByRole('row', { name: new RegExp(`#${N}`) }).innerText()), 'Compra aparece como paga')

secao('Excluir pagamento e compra')
await page.getByRole('row', { name: new RegExp(`#${N}`) }).click(); await espera(400)
await page.getByRole('button', { name: /Ver pagamentos/ }).click(); d = dialog(page)
await d.getByRole('button', { name: /Excluir pagamento de R\$\s?40,00/ }).click(); await dialog(page).last().getByRole('button', { name: 'Excluir' }).click(); await espera(1500)
ok(pagoDe(N) === 160 && saldoConta('Mercado Pago') === S0 - 160, 'Excluir um pagamento devolve o valor ao saldo')
await page.keyboard.press('Escape'); await espera(300)
await page.getByRole('button', { name: 'Nova compra' }).click(); d = dialog(page)
await d.getByLabel('Item', { exact: false }).first().selectOption({ label: 'Fone Bluetooth X' })
await d.getByLabel(/^Qtd\./).first().fill('1'); await d.getByLabel(/^Preço por/).first().fill('50'); await d.getByLabel(/Já recebi/).uncheck()
await d.getByRole('button', { name: 'Tudo' }).click()
ok((await d.getByLabel('Pago agora (R$)').inputValue()) === '50', 'Botão "Tudo" preenche o total')
await d.getByRole('button', { name: 'Lançar compra' }).click(); await espera(1500)
const N2 = ultima()
ok(saldoConta('Mercado Pago') === S0 - 210, 'Compra paga à vista desconta na hora')
await page.getByRole('button', { name: `Excluir compra ${N2}` }).click(); await dialog(page).last().getByRole('button', { name: /Excluir|Confirmar/ }).click(); await espera(1500)
ok(SQL(`select count(*) from compra where empresa_id='${EMP}' and numero=${N2}`) === '0' && saldoConta('Mercado Pago') === S0 - 160, 'Excluir compra pedida apaga os pagamentos e devolve ao saldo')

secao('Pela API')
const r = await page.evaluate(async (num) => {
  const k = Object.keys(localStorage).find((x) => x.includes('auth-token')); const s = JSON.parse(localStorage.getItem(k))
  const h = { apikey: s.access_token, Authorization: 'Bearer ' + s.access_token, 'Content-Type': 'application/json' }
  const c = await (await fetch(`http://localhost:54321/rest/v1/compra?numero=eq.${num}&select=id,conta_id`, { headers: h })).json()
  const contas = await (await fetch('http://localhost:54321/rest/v1/conta_financeira?select=id&padrao=eq.true', { headers: h })).json()
  const ins = await fetch('http://localhost:54321/rest/v1/compra_pagamento', { method: 'POST', headers: h, body: JSON.stringify({ compra_id: c[0].id, conta_id: contas[0].id, valor: 1000 }) })
  const neg = await fetch('http://localhost:54321/rest/v1/compra_pagamento', { method: 'POST', headers: h, body: JSON.stringify({ compra_id: c[0].id, conta_id: contas[0].id, valor: -5 }) })
  return { ins: ins.status, txt: (await ins.text()).slice(0, 120), neg: neg.status }
}, N)
ok(r.ins >= 400 && /passa do total.*R\$ 40,00/.test(r.txt), 'Banco recusa pagamento acima do total', r.txt)
ok(r.neg >= 400, 'Banco recusa pagamento negativo')
const OP = `operpg${Date.now()}@teste.com`; await novoUsuario(OP)
SQL(`insert into membro(empresa_id,user_id,papel) select '${EMP}', id, 'operador' from auth.users where email='${OP}'`)
SQL(`update usuario set empresa_atual='${EMP}' where email='${OP}'`)
const tk = await (await fetch('http://localhost:54321/auth/v1/token?grant_type=password', { method: 'POST', headers: { apikey: KEYS_.ANON_KEY, 'Content-Type': 'application/json' }, body: JSON.stringify({ email: OP, password: 'Senha@123' }) })).json()
const hOp = { apikey: KEYS_.ANON_KEY, Authorization: 'Bearer ' + tk.access_token, 'Content-Type': 'application/json' }
const vis = await (await fetch('http://localhost:54321/rest/v1/compra_pagamento?select=*', { headers: hOp })).json()
const vf = await (await fetch('http://localhost:54321/rest/v1/vw_compra_financeiro?select=*', { headers: hOp })).json()
ok(Array.isArray(vis) && vis.length === 0 && Array.isArray(vf) && vf.length === 0, 'Operador não vê pagamentos nem valores a pagar')
const cid = SQL(`select id from compra where empresa_id='${EMP}' and numero=${N}`), contaId = SQL(`select id from conta_financeira where empresa_id='${EMP}' and padrao`)
const insOp = await fetch('http://localhost:54321/rest/v1/compra_pagamento', { method: 'POST', headers: hOp, body: JSON.stringify({ compra_id: cid, conta_id: contaId, valor: 1 }) })
ok(insOp.status >= 400 && pagoDe(N) === 160, 'Operador não lança pagamento', String(insOp.status))

ok(erros.length === 0, 'Sem erros de JavaScript', erros.slice(0, 3).join(' / '))
await b.close()
salvar('/tmp/claude-0/e2e/r12.json')
