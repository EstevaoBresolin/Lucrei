// Meta Pixel: eventos só nos momentos certos (lê a fila do fbq, já que o script do Facebook não carrega aqui)
import { abrir, APP, ok, secao, salvar, espera, SQL, novoUsuario, entrar } from './lib.mjs'
const idDe = (page, ev) => page.evaluate((e) => (window.fbq?.queue ?? []).find((a) => a[1] === e)?.[3]?.eventID ?? null, ev)
const eventos = (page) => page.evaluate(() => (window.fbq?.queue ?? []).map((a) => [...a].slice(0, 2).join(':')))
const { b, page } = await abrir()
await page.route(/connect\.facebook\.net/, (r) => r.abort())

secao('PageView e cadastro')
await page.goto(APP + '/'); await espera(1200)
ok((await eventos(page)).includes('init:1155281290345367') && (await eventos(page)).includes('track:PageView'), 'Pixel inicia e manda PageView na landing', (await eventos(page)).join(', '))
const EM = `pixel${Date.now()}@teste.com`
await page.goto(APP + '/cadastro'); await espera(800)
await page.getByLabel('Seu nome').fill('Pixel Teste'); await page.getByLabel('E-mail').fill(EM); await page.getByLabel('Senha').fill('Senha@123')
await page.getByRole('button', { name: 'Criar conta', exact: true }).click(); await espera(1200)
let ev = await eventos(page)
ok(!ev.includes('track:CompleteRegistration'), 'Sem aceitar os termos (erro) não dispara cadastro', ev.join(', '))
await page.getByRole('checkbox').check(); await page.getByRole('button', { name: 'Criar conta', exact: true }).click(); await espera(2500)
ev = await eventos(page)
ok(ev.filter((e) => e === 'track:CompleteRegistration').length === 1, 'Conta criada dispara CompleteRegistration uma vez', ev.join(', '))
ok(!ev.includes('track:StartTrial'), 'Só criar a conta ainda não é StartTrial')
const id1 = await idDe(page, 'CompleteRegistration')

secao('E-mail repetido')
const { b: b2, page: p2 } = await abrir(); await p2.route(/connect\.facebook\.net/, (r) => r.abort())
await p2.goto(APP + '/cadastro'); await espera(800)
await p2.getByLabel('Seu nome').fill('Repetido'); await p2.getByLabel('E-mail').fill(EM); await p2.getByLabel('Senha').fill('Senha@123')
await p2.getByRole('checkbox').check(); await p2.getByRole('button', { name: 'Criar conta', exact: true }).click(); await espera(2500)
const id2 = await idDe(p2, 'CompleteRegistration')
ok(id2 === null || id2 === id1, 'Cadastro refeito com o mesmo e-mail usa o mesmo ID (o Meta conta uma vez só)', `${id1} / ${id2}`)
await b2.close()

secao('Início do teste grátis')
const EM2 = `pixel2${Date.now()}@teste.com`; await novoUsuario(EM2)
const { b: b3, page: p3 } = await abrir(); await p3.route(/connect\.facebook\.net/, (r) => r.abort())
await entrar(p3, EM2); await espera(1000)
await p3.getByRole('button', { name: 'Criar minha empresa' }).click(); await espera(800)
ok(!(await eventos(p3)).includes('track:StartTrial'), 'Empresa sem nome (erro) não dispara StartTrial')
await p3.getByLabel('Nome da loja ou empresa').fill('Loja Pixel'); await p3.getByText('Compro pronto e revendo').click()
await p3.getByRole('button', { name: 'Criar minha empresa' }).click(); await p3.locator('aside').waitFor({ timeout: 15000 }).catch(() => {})
ev = await eventos(p3)
ok(ev.filter((e) => e === 'track:StartTrial').length === 1, 'Empresa criada dispara StartTrial uma vez', ev.join(', '))
const det = await p3.evaluate(() => { const q = (window.fbq?.queue ?? []).find((a) => a[1] === 'StartTrial'); return q ? JSON.stringify([q[2], Object.keys(q[3] ?? {})]) : '' })
ok(/"currency":"BRL"/.test(det) && /eventID/.test(det), 'StartTrial leva moeda e eventID (para não duplicar com o servidor depois)', det)
secao('Assinatura (InitiateCheckout)')
await p3.route('**/__fatura/**', (r) => r.abort()) // segura a página aqui para ler a fila do pixel
await p3.goto(APP + '/assinatura'); await p3.getByText('Situação').waitFor()
await p3.getByRole('button', { name: /Assinar/ }).first().click(); await espera(800)
ok(!(await eventos(p3)).includes('track:InitiateCheckout'), 'Sem CPF (erro) não dispara InitiateCheckout')
const gravados = []
await p3.exposeFunction('__grava', (x) => gravados.push(x))
await p3.evaluate(() => { const orig = window.fbq; window.fbq = function (...a) { window.__grava(JSON.stringify(a)); return orig.apply(this, a) } })
await p3.getByLabel(/CPF ou CNPJ/).fill('52998224725'); await p3.getByRole('button', { name: /Assinar/ }).first().click(); await espera(3000)
const ck = JSON.stringify(gravados.map((x) => JSON.parse(x)).filter((a) => a[1] === 'InitiateCheckout').map((a) => [a[2], a[3]]))
ok(/"currency":"BRL"/.test(ck) && /"value":\d/.test(ck) && JSON.parse(ck).length === 1, 'Assinar dispara InitiateCheckout uma vez, com o valor do plano, antes de ir para o Asaas', ck)
await b3.close(); await b.close()
salvar('/tmp/claude-0/e2e/r13.json')
