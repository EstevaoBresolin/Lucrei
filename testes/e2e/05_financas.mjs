import { abrir, APP, ok, nota, secao, salvar, shot, espera, SQL, dialog, textoErro, toast } from './lib.mjs'
const { b, page, erros } = await abrir({ storageState: '/tmp/claude-0/e2e/dono.json' })
const EMP = SQL("select id from empresa where nome='Fábrica Teste'")
const saldoConta = (n) => Number(SQL(`select set_config('request.jwt.claim.role','service_role',false), set_config('app.empresa','${EMP}',false); select saldo from vw_conta_saldo where nome='${n}' and empresa_id='${EMP}'`).split('\n').pop())

secao('Finanças — primeira conta')
await page.goto(APP + '/financas'); await espera(1500)
if (await page.getByRole('button', { name: 'Começar' }).count()) {
  const nomePadrao = await page.getByLabel('Nome da conta').inputValue()
  nota('Nome sugerido da conta', nomePadrao || '(vazio)')
  await page.getByLabel('Nome da conta').fill('')
  await page.getByRole('button', { name: 'Começar' }).click()
  ok(/Dê um nome à conta/.test(await textoErro(page)), 'Conta sem nome é bloqueada')
  await page.getByLabel('Nome da conta').fill('Mercado Pago'); await page.getByLabel('Saldo disponível hoje (R$)').fill('1.500,50')
  await page.getByRole('button', { name: 'Começar' }).click(); await espera(1500)
  ok(saldoConta('Mercado Pago') === 1500.5, 'Conta criada com saldo 1.500,50 (milhar com ponto)', String(saldoConta('Mercado Pago')))
}
const S0 = saldoConta('Mercado Pago')
secao('Lançamentos')
await page.getByRole('button', { name: /Lançar|Entrada ou saída|Novo lançamento/ }).last().click(); let d = dialog(page)
await d.getByRole('button', { name: 'Salvar' }).click()
ok(/Informe o valor/.test(await textoErro(d)), 'Lançamento sem valor é bloqueado')
await d.getByLabel('Valor (R$)').fill('200'); await d.getByRole('button', { name: 'Salvar' }).click()
ok(/Descreva o lançamento/.test(await textoErro(d)), 'Lançamento sem descrição é bloqueado')
await d.getByLabel('Descrição').fill('Retirada de lucro'); await d.getByRole('button', { name: 'Salvar' }).click(); await espera(1200)
ok(saldoConta('Mercado Pago') === S0 - 200, 'Saída de 200 baixa o saldo', String(saldoConta('Mercado Pago')))
if (await dialog(page).count()) { nota('Modal de lançamento', 'continuou aberto depois de salvar'); await page.keyboard.press('Escape'); await dialog(page).getByRole('button', { name: 'Cancelar' }).click().catch(() => {}) }
await page.getByRole('button', { name: 'Entrada ou saída' }).click(); d = dialog(page)
await d.getByRole('button', { name: 'Entrada (dinheiro entrou)', exact: true }).click(); await d.getByLabel('Descrição').fill('Aporte'); await d.getByLabel('Valor (R$)').fill('50')
await d.getByRole('button', { name: 'Salvar' }).click(); await espera(1200)
ok(saldoConta('Mercado Pago') === S0 - 150, 'Entrada de 50 sobe o saldo', String(saldoConta('Mercado Pago')))

secao('Contas, transferência e conferência')
await page.getByRole('button', { name: 'Contas' }).click(); d = dialog(page)
await d.getByRole('button', { name: /Nova conta/ }).click()
await d.getByRole('button', { name: 'Salvar' }).click()
ok(/Dê um nome à conta/.test(await textoErro(d)), 'Nova conta sem nome é bloqueada')
await d.getByLabel('Nome').fill('mercado pago'); await d.getByRole('button', { name: 'Salvar' }).click()
ok(/Já existe uma conta/.test(await textoErro(d)), 'Conta com nome repetido é bloqueada')
await d.getByLabel('Nome').fill('Caixa da loja'); await d.getByLabel('Saldo inicial (R$)').fill('-20')
ok((await d.getByLabel('Saldo inicial (R$)').inputValue()) === '-20', 'Saldo inicial aceita negativo (conta no vermelho)')
await d.getByLabel('Saldo inicial (R$)').fill('100'); await d.getByRole('button', { name: 'Salvar' }).click(); await espera(1200)
if (await d.isVisible()) await d.getByRole('button', { name: /Fechar|Voltar/ }).first().click().catch(() => page.keyboard.press('Escape'))
await page.reload(); await espera(1200)
ok(saldoConta('Caixa da loja') === 100, 'Segunda conta criada')
await page.getByRole('button', { name: 'Transferir' }).click(); d = dialog(page)
await d.getByLabel('Valor (R$)').fill('30'); await d.locator('select').nth(0).selectOption({ label: 'Caixa da loja' }); await d.locator('select').nth(1).selectOption({ label: 'Caixa da loja' })
await d.getByRole('button', { name: 'Transferir' }).click()
ok(/duas contas diferentes/.test(await textoErro(d)), 'Transferir para a mesma conta é bloqueado')
await d.locator('select').nth(1).selectOption({ label: 'Mercado Pago' }); await d.getByRole('button', { name: 'Transferir' }).click(); await espera(1200)
ok(saldoConta('Caixa da loja') === 70 && saldoConta('Mercado Pago') === S0 - 120, 'Transferência move o dinheiro', `${saldoConta('Caixa da loja')} / ${saldoConta('Mercado Pago')}`)
await page.getByRole('button', { name: 'Conferir saldo' }).click(); d = dialog(page)
await d.getByRole('button', { name: /Conferir|Lançar ajuste/ }).click()
ok(/Informe o saldo/.test(await textoErro(d)), 'Conferir sem informar o saldo é bloqueado')
await d.getByLabel(/Saldo disponível de verdade/).fill(String(S0 + 1000).replace('.', ',')); await d.getByRole('button', { name: /Lançar ajuste/ }).click(); await espera(1200)
ok(saldoConta('Mercado Pago') === S0 + 1000, 'Conferência lança o ajuste da diferença', String(saldoConta('Mercado Pago')))
const ext = await page.locator('main').innerText()
ok(/Retirada de lucro/.test(ext) && /Ajuste de saldo/.test(ext), 'Extrato mostra os lançamentos')
await page.getByText('Retirada de lucro').first().click(); d = dialog(page)
await d.getByLabel('Valor (R$)').fill('250'); await d.getByRole('button', { name: 'Salvar' }).click(); await espera(1200)
ok(saldoConta('Mercado Pago') === S0 + 950, 'Editar lançamento recalcula o saldo', String(saldoConta('Mercado Pago')))
await page.getByText('Retirada de lucro').first().click(); d = dialog(page)
await d.getByRole('button', { name: 'Excluir' }).click(); if (await page.getByRole('dialog').count() > 1) await page.getByRole('dialog').last().getByRole('button', { name: 'Excluir' }).click()
await espera(1200)
ok(saldoConta('Mercado Pago') === S0 + 1200, 'Excluir lançamento', String(saldoConta('Mercado Pago')))
await shot(page, '10-financas')

secao('Despesas')
await page.goto(APP + '/financeiro'); await espera(1000)
await page.getByRole('button', { name: /Nova despesa/ }).click(); d = dialog(page)
await d.getByRole('button', { name: 'Lançar despesa' }).click()
ok(/Informe a descrição e o valor/.test(await textoErro(d)), 'Despesa vazia é bloqueada')
await d.getByLabel('Descrição').fill('Anúncios Mercado Ads'); await d.getByLabel('Valor (R$)').fill('-50')
ok(!(await d.getByLabel('Valor (R$)').inputValue()).includes('-'), 'Valor da despesa não aceita negativo', await d.getByLabel('Valor (R$)').inputValue())
await d.getByLabel('Valor (R$)').fill('89,90'); await d.getByLabel('Categoria').selectOption({ label: 'Anúncios' })
const rec = d.getByLabel(/Repete todo mês|recorrente/i); if (await rec.count()) await rec.check()
await d.getByRole('button', { name: 'Lançar despesa' }).click(); await espera(1200)
ok(SQL("select count(*) from despesa where descricao='Anúncios Mercado Ads'") === '1', 'Despesa salva')
ok(Math.abs(saldoConta('Mercado Pago') - (S0 + 1110.1)) < 0.001, 'Despesa sai da conta padrão', String(saldoConta('Mercado Pago')))
await page.getByText('Anúncios Mercado Ads').click(); d = dialog(page); await d.getByLabel('Valor (R$)').fill('99,90'); await d.getByRole('button', { name: 'Salvar' }).click(); await espera(1000)
ok(Number(SQL("select valor from despesa where descricao='Anúncios Mercado Ads'")) === 99.9, 'Editar despesa')
const mesSeg = new Date(); mesSeg.setMonth(mesSeg.getMonth() + 1)
await page.locator('input[type=month]').fill(mesSeg.toISOString().slice(0, 7)); await espera(800)
const copiar = page.getByRole('button', { name: /recorrente|Copiar/i })
if (await copiar.count()) { await copiar.first().click(); await espera(400); if (await page.getByRole('dialog').count()) await page.getByRole('dialog').getByRole('button').last().click(); await espera(1200)
  ok(Number(SQL("select count(*) from despesa where descricao='Anúncios Mercado Ads'")) === 2, 'Copiar despesas recorrentes para o mês seguinte') }
await page.locator('input[type=month]').fill(new Date().toISOString().slice(0, 7)); await espera(800)
await page.getByRole('button', { name: 'Excluir' }).first().click(); await espera(300); if (await page.getByRole('dialog').count()) await page.getByRole('dialog').getByRole('button', { name: 'Excluir' }).click()
await espera(1000)
ok(SQL("select count(*) from despesa where data <= current_date") === '0', 'Excluir despesa')
ok(erros.length === 0, 'Sem erros de JavaScript', erros.slice(0, 3).join(' / '))
salvar('/tmp/claude-0/e2e/r05.json'); await b.close()
